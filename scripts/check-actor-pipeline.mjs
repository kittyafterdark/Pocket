import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import { mkdir, readFile } from 'node:fs/promises'
import { spawnSync } from 'node:child_process'
import { createServer } from 'node:http'
import { fileURLToPath } from 'node:url'
import { resolve } from 'node:path'

const root = fileURLToPath(new URL('../', import.meta.url)), output = resolve(root, 'tmp/actor-pipeline')
await mkdir(output, { recursive: true })
const build = spawnSync('bun', ['build', 'tests/fixtures/launcher-browser.ts', '--target=browser', '--format=iife', `--outfile=${output}/preview.js`], { cwd: root, encoding: 'utf8' })
if (build.status !== 0) throw build.error || new Error(build.stderr)
const require = createRequire(import.meta.url), paths = [process.env.POCKET_PLAYWRIGHT_ROOT, resolve(root, '../../LumiTest/Lumiverse/scripts/e2e-diagnostics'), process.env.NODE_PATH].filter(Boolean)
const { chromium } = require(require.resolve('playwright', { paths })), script = await readFile(resolve(output, 'preview.js'))
const server = createServer((request, response) => {
  if (request.url.startsWith('/preview.js')) { response.setHeader('Content-Type', 'text/javascript'); response.end(script) }
  else if (request.url.startsWith('/photo.svg')) { response.setHeader('Content-Type', 'image/svg+xml'); response.end('<svg xmlns="http://www.w3.org/2000/svg" width="200" height="200"><rect width="200" height="200" fill="#b89ce3"/></svg>') }
  else response.end('<!doctype html><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><script src="/preview.js" defer></script>')
})
await new Promise(done => server.listen(0, '127.0.0.1', done))
let browser, activePage
try {
  browser = await chromium.launch({ headless: true, executablePath: process.env.POCKET_CHROMIUM_EXECUTABLE || undefined })
  for (const width of [390, 900]) {
    const page = await browser.newPage({ viewport: { width, height: 844 }, isMobile: width === 390, hasTouch: width === 390 }); activePage = page
    const errors = []; page.on('pageerror', error => errors.push(error.message)); page.setDefaultTimeout(10000)
    await page.goto(`http://127.0.0.1:${server.address().port}/?actorPipeline`)
    await page.getByRole('button', { name: 'Open Pocket', exact: true }).waitFor()
    await page.evaluate(() => {
      window.deliverSocialOperationFixture({ type: 'lumiphone:capabilities', capabilities: { panels: true, generation: true, images: true, imageGen: true } })
      window.seedActorPipelineFixture()
    })
    const press = async name => {
      const button = page.getByRole('button', { name, exact: true })
      return width === 390 ? button.tap() : button.click()
    }
    const openApp = async name => { await press('Home or dismiss phone'); await press('Open app drawer'); await press(name) }
    await press('Open Pocket'); await press('Open app drawer'); await press('Messages')
    await page.locator('.lp-conversation-row').filter({ hasText: 'Fern Vale' }).click()
    await page.getByLabel('Conversation menu', { exact: true }).click(); await press('Contact info')
    await page.getByRole('button', { name: 'Describe from phone context ✦', exact: true }).waitFor()
    await page.screenshot({ path: resolve(output, `discovered-profile-${width}.png`) })
    await press('Describe from phone context ✦')
    await page.getByText('A florist known through phone exchanges.', { exact: true }).waitFor()
    await press('Save to NPC Bank')
    await page.getByRole('button', { name: 'Update NPC Bank', exact: true }).waitFor()
    await press('‹ Back')
    await page.locator('.lp-bubble').filter({ hasText: 'The flower shop closes at six.' }).waitFor({ state: 'visible' })
    const snapshot = await page.evaluate(() => window.actorPipelineSnapshot())
    assert.equal(snapshot.state.contacts.length, 1)
    assert.ok(snapshot.state.contacts[0].source.bankId, 'Discovered actor is linked to NPC Bank')
    await openApp('Contacts'); await press('Add'); await press('Import from lorebook')
    let dialog = page.getByRole('dialog', { name: 'Import from lorebook', exact: true })
    await dialog.getByRole('button', { name: 'Town lore This chat', exact: true }).click()
    await dialog.getByRole('searchbox', { name: 'Find source entries', exact: true }).fill('an')
    assert.match(await dialog.getByRole('checkbox').first().evaluate(node => node.labels[0].textContent), /^An Kohinata/, 'Character name ranks above incidental substrings')
    await dialog.getByRole('searchbox', { name: 'Find source entries', exact: true }).fill('')
    await dialog.getByRole('checkbox', { name: 'Town residents', exact: true }).check()
    await dialog.getByText('Preview Town residents', { exact: true }).click()
    assert.ok(await dialog.getByText('Fern owns a flower shop. Mika owns a cafe.', { exact: true }).isVisible())
    await dialog.getByRole('button', { name: 'All lorebooks', exact: true }).click()
    await dialog.getByRole('searchbox', { name: 'Search lorebooks', exact: true }).fill('Daily')
    assert.equal(await dialog.getByRole('button', { name: 'Town lore This chat', exact: true }).count(), 0)
    await dialog.getByRole('searchbox', { name: 'Search lorebooks', exact: true }).fill('')
    await page.evaluate(() => window.refreshLauncherFixture())
    assert.equal(await dialog.getByRole('checkbox', { name: 'Town residents', exact: true }).isChecked(), true, 'Background refresh preserves source selection')
    await dialog.getByRole('button', { name: 'Daily life Character', exact: true }).click()
    await dialog.getByRole('checkbox', { name: 'Evening routines', exact: true }).check()
    assert.ok(await dialog.getByText('2 source entries selected across 2 lorebooks', { exact: true }).isVisible())
    assert.equal(await dialog.evaluate(node => node.scrollWidth > node.clientWidth + 1), false, 'Dialog has no horizontal overflow')
    const findBounds = await dialog.getByRole('button', { name: 'Find NPCs', exact: true }).boundingBox()
    assert.ok(findBounds.x >= 0 && findBounds.x + findBounds.width <= width, 'Find NPCs stays on screen')
    const bounds = await dialog.boundingBox()
    if (width === 900) { assert.ok(bounds.width > 700, 'Desktop uses a wide viewport dialog'); assert.ok(Math.abs(bounds.x + bounds.width / 2 - width / 2) < 2, 'Desktop dialog is centered outside the phone') }
    assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= width + 1, 'Picker fits viewport width')
    if (width === 390) assert.ok(bounds.y >= 47, 'Picker respects the host safe-top region')
    await page.screenshot({ path: resolve(output, `lorebook-picker-${width}.png`) })
    await page.keyboard.press('Escape'); await dialog.waitFor({ state: 'detached' })
    assert.ok(await page.getByRole('button', { name: 'Import from lorebook', exact: true }).evaluate(node => document.activeElement === node), 'Escape restores opener focus')
    await page.getByRole('button', { name: 'Import from lorebook', exact: true }).focus(); await page.keyboard.press('Enter')
    dialog = page.getByRole('dialog', { name: 'Import from lorebook', exact: true })
    await dialog.getByRole('button', { name: 'Town lore This chat', exact: true }).click()
    await dialog.getByRole('searchbox', { name: 'Find source entries', exact: true }).fill('Town')
    await dialog.getByRole('checkbox', { name: 'Town residents', exact: true }).check()
    await dialog.getByRole('button', { name: 'Daily life Character', exact: true }).click()
    await dialog.getByRole('checkbox', { name: 'Evening routines', exact: true }).check()
    await dialog.getByText('Looking for specific people?', { exact: true }).click()
    await dialog.getByRole('textbox', { name: 'People to find (optional)', exact: true }).fill('Fern and Mika')
    await dialog.getByRole('button', { name: 'Find NPCs', exact: true }).click()
    await dialog.getByRole('heading', { name: 'Finding your NPCs', exact: true }).waitFor()
    await dialog.getByRole('progressbar', { name: 'Reading source entries', exact: true }).waitFor()
    assert.equal(await dialog.getByRole('progressbar').getAttribute('value'), '1')
    await page.screenshot({ path: resolve(output, `lorebook-progress-${width}.png`) })
    await dialog.getByRole('status').filter({ hasText: 'Writing profiles' }).waitFor()
    await dialog.getByRole('heading', { name: 'Review NPCs', exact: true }).waitFor()
    if (width === 390) assert.ok((await dialog.boundingBox()).y >= 47, 'Review respects host safe top')
    assert.equal(await dialog.getByRole('checkbox', { name: 'Add Fern Vale', exact: true }).isChecked(), false, 'Existing profiles start unchecked')
    assert.equal(await dialog.getByRole('checkbox', { name: 'Add Mika Moon', exact: true }).isChecked(), true)
    await dialog.getByRole('group', { name: 'Mika Moon', exact: true }).getByRole('textbox', { name: 'Name', exact: true }).fill('Mika Star')
    const request = await page.evaluate(() => window.lastLorebookRequest)
    assert.deepEqual(request.sources, [{ bookId: 'people', entryId: 'cast' }, { bookId: 'supplement', entryId: 'details' }])
    assert.equal(request.people, 'Fern and Mika')
    assert.equal((await page.evaluate(() => window.actorPipelineSnapshot())).state.contacts.length, 1, 'Extraction does not save contacts')
    await dialog.getByRole('heading', { name: 'Review NPCs', exact: true }).focus()
    await dialog.locator('.lp-lorebook-review-grid').evaluate(node => { node.scrollTop = 0 })
    await page.screenshot({ path: resolve(output, `lorebook-review-${width}.png`) })
    await dialog.getByRole('button', { name: 'Save 1 selected contact', exact: true }).click()
    await dialog.getByText('Added 1 contact. Reused 0 existing profiles.', { exact: true }).waitFor()
    const resultPanel = dialog.locator('.lp-lorebook-result')
    assert.ok(await resultPanel.evaluate(node => parseFloat(getComputedStyle(node).paddingLeft) >= 18), 'Completion content has a padded margin')
    const doneBounds = await dialog.getByRole('button', { name: 'Done', exact: true }).boundingBox(), dialogBounds = await dialog.boundingBox()
    assert.ok(doneBounds.x > dialogBounds.x + 18 && doneBounds.x + doneBounds.width < dialogBounds.x + dialogBounds.width - 18, 'Done does not touch modal edges')
    await page.screenshot({ path: resolve(output, `lorebook-complete-${width}.png`) })
    const imported = await page.evaluate(() => window.actorPipelineSnapshot())
    assert.equal(imported.state.contacts.length, 2)
    assert.equal(imported.state.contacts.find(contact => contact.name === 'Mika Star').identityBrief, 'Owns a cafe and texts briefly.')
    await dialog.getByRole('button', { name: 'Done', exact: true }).click()
    await page.waitForTimeout(100)
    assert.ok(await page.getByRole('button', { name: 'Generate NPC', exact: true }).isEnabled(), 'Completed extraction and late progress do not leave the manual generator busy')
    await page.evaluate(() => window.remountContactsMediaFixture())
    await page.getByRole('button', { name: 'Open Pocket', exact: true }).waitFor()
    await press('Open Pocket'); await press('Open app drawer'); await press('Messages')
    await page.locator('.lp-conversation-row').filter({ hasText: 'Fern Vale' }).click()
    await page.locator('.lp-bubble').filter({ hasText: 'The flower shop closes at six.' }).waitFor({ state: 'visible' })
    await page.evaluate(() => window.seedActorPipelineFixture())
    await page.getByLabel('Conversation menu', { exact: true }).click(); await press('Contact info')
    await press('Home or dismiss phone')
    await page.waitForTimeout(180)
    assert.equal(await page.getByRole('button', { name: 'Describe from phone context ✦', exact: true }).count(), 0, 'Late promotion cannot reopen a profile after leaving its chat')
    assert.equal(errors.length, 0, errors.join('\n'))
    console.log(`Actor profile, Back, NPC Bank, lorebook selection, keyboard and remount checks passed at ${width}px`)
    await page.close()
  }
} catch (error) {
  if (activePage && !activePage.isClosed()) { await activePage.screenshot({ path: resolve(output, 'failure.png') }); console.error((await activePage.locator('body').innerText()).slice(0, 4000)) }
  throw error
} finally { await browser?.close(); await new Promise(done => server.close(done)) }
